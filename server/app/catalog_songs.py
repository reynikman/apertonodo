"""Song = studio recording, the rest are its versions (catalog v2, V3).

`python -m app.catalog_songs build`

Grouping recordings: MusicBrainz work and same artist, otherwise
(artist, normalized title). A recording without a work joins the
only work-group of the same artist with the same title_key. Version kind —
recording->work relationship attributes, recording comment, title tail
(parentheses / after dash at the end) and secondary types of the first release. Studio
original — among kind=original on official Album/Single/EP without secondary
types; in case of ties Album takes precedence over earlier Single (V3 review), then
earlier date, then more ISRCs and releases. Live and remix never qualify.

Build is set-based SQL, without a row-by-row loop. Swap is a single transaction.
Called after genre build at the end of `python -m app.mbcopy load`. Screens in V5.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import os
import sys
import time
from collections.abc import Callable
from typing import Any

import asyncpg

from app import search_indexes

logger = logging.getLogger("apertonodo")

MAINTENANCE_WORK_MEM = "512MB"
KINDS = (
    "original",
    "remaster",
    "live",
    "demo",
    "acoustic",
    "remix",
    "rerecording",
    "instrumental",
    "cover",
    "other",
)

# Title tails — only parentheses at the end and " - …" / " – …" at the end.
# Do not touch the middle: otherwise "Live Forever" would merge with "Forever".
TAIL_MARK = (
    "live|demo|acoustic|remix|remaster(?:ed)?|version|deluxe|edition|"
    "anniversary|instrumental|karaoke|cover|rerecording|re-recording"
)

_swap_hook: Callable[[], Any] | None = None


def title_key_sql(col: str) -> str:
    """Normalization canonical.normalize_text, tails only at the end of the title."""
    return f"""
    trim(both from regexp_replace(
      regexp_replace(
        regexp_replace(
          regexp_replace(
            lower(normalize({col}, NFKC)),
            '\\s*[\\(\\[][^\\)\\]]*?(?:{TAIL_MARK})[^\\)\\]]*[\\)\\]]\\s*$',
            '',
            'gi'
          ),
          '\\s*[-–]\\s+(?:(?![-–]).)*(?:{TAIL_MARK}).*$',
          '',
          'gi'
        ),
        '[^\\w\\s]+',
        ' ',
        'g'
      ),
      '\\s+',
      ' ',
      'g'
    ))
    """


def title_has_tail_sql(col: str, pattern: str) -> str:
    """Version kind keyword only in the tail of the title, not in the middle."""
    return (
        f"({col} ~* '[\\(\\[][^\\)\\]]*\\y(?:{pattern})\\y[^\\)\\]]*[\\)\\]]\\s*$'"
        f" OR {col} ~* '\\s[-–]\\s+.*\\y(?:{pattern})\\y.*$')"
    )


async def _has_mb(conn: asyncpg.Connection) -> bool:
    return bool(await conn.fetchval("SELECT 1 FROM pg_tablespace WHERE spcname = 'mb'"))


async def _drop_load(conn: asyncpg.Connection) -> None:
    await conn.execute("DROP TABLE IF EXISTS song_version_load")
    await conn.execute("DROP TABLE IF EXISTS song_load")
    await conn.execute("DROP TABLE IF EXISTS song_rec")
    await conn.execute("DROP TABLE IF EXISTS song_first")
    await conn.execute("DROP TABLE IF EXISTS song_studio")


async def _create_load(conn: asyncpg.Connection, has_mb: bool, hot_on_main: bool) -> None:
    def ts(name: str) -> str:
        return search_indexes.relation_tablespace(name, has_mb=has_mb, hot_on_main=hot_on_main)

    await _drop_load(conn)
    await conn.execute(
        f"""
        CREATE UNLOGGED TABLE song_first (
            recording_mbid uuid PRIMARY KEY,
            group_mbid uuid,
            primary_type text,
            secondary_types text[] NOT NULL DEFAULT '{{}}',
            first_date text,
            status text,
            year smallint
        ){ts("song_first")}
        """
    )
    await conn.execute(
        f"""
        CREATE UNLOGGED TABLE song_studio (
            recording_mbid uuid PRIMARY KEY,
            studio_date text,
            type_rank integer NOT NULL,
            editions integer NOT NULL
        ){ts("song_studio")}
        """
    )
    await conn.execute(
        f"""
        CREATE UNLOGGED TABLE song_rec (
            recording_mbid uuid PRIMARY KEY,
            artist_mbid uuid NOT NULL,
            title text NOT NULL,
            title_key text NOT NULL,
            group_key text NOT NULL,
            work_mbid uuid,
            kind text NOT NULL,
            year smallint,
            studio_date text,
            type_rank integer,
            editions integer NOT NULL DEFAULT 0,
            isrcs integer NOT NULL DEFAULT 0
        ){ts("song_rec")}
        """
    )
    await conn.execute(
        f"""
        CREATE TABLE song_load (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            group_key text NOT NULL UNIQUE,
            artist_mbid uuid NOT NULL,
            title text NOT NULL,
            work_mbid uuid,
            original_recording_mbid uuid,
            original_year smallint
        ){ts("song_load")}
        """
    )
    await conn.execute(
        f"""
        CREATE TABLE song_version_load (
            song_id bigint NOT NULL REFERENCES song_load(id),
            recording_mbid uuid NOT NULL PRIMARY KEY,
            kind text NOT NULL,
            year smallint
        ){ts("song_version_load")}
        """
    )
    await conn.execute(
        f"CREATE INDEX song_version_load_song ON song_version_load (song_id){ts('song_version_load_song')}"
    )


async def _fill(conn: asyncpg.Connection) -> dict[str, Any]:
    await conn.execute(
        """
        INSERT INTO song_first (
            recording_mbid, group_mbid, primary_type, secondary_types,
            first_date, status, year
        )
        SELECT DISTINCT ON (t.recording_mbid)
            t.recording_mbid,
            rg.mbid,
            rg.primary_type,
            COALESCE(rg.secondary_types, '{}'),
            COALESCE(NULLIF(rg.first_date, ''), r.date),
            r.status,
            CASE
                WHEN COALESCE(NULLIF(rg.first_date, ''), r.date) ~ '^[0-9]{4}'
                THEN substr(COALESCE(NULLIF(rg.first_date, ''), r.date), 1, 4)::smallint
            END
        FROM mb_track t
        JOIN mb_medium m ON m.id = t.medium_id
        JOIN mb_release r ON r.mbid = m.release_mbid
        JOIN mb_release_group rg ON rg.mbid = r.group_mbid
        ORDER BY t.recording_mbid,
                 COALESCE(NULLIF(rg.first_date, ''), r.date) NULLS LAST,
                 r.mbid
        """
    )
    await conn.execute(
        """
        INSERT INTO song_studio (recording_mbid, studio_date, type_rank, editions)
        SELECT t.recording_mbid,
               min(COALESCE(NULLIF(rg.first_date, ''), r.date)),
               min(CASE rg.primary_type
                     WHEN 'Album' THEN 0
                     WHEN 'Single' THEN 1
                     WHEN 'EP' THEN 2
                     ELSE 9
                   END),
               count(DISTINCT r.mbid)::integer
        FROM mb_track t
        JOIN mb_medium m ON m.id = t.medium_id
        JOIN mb_release r ON r.mbid = m.release_mbid
        JOIN mb_release_group rg ON rg.mbid = r.group_mbid
        WHERE r.status = 'Official'
          AND rg.primary_type IN ('Album', 'Single', 'EP')
          AND COALESCE(rg.secondary_types, '{}') = '{}'
        GROUP BY t.recording_mbid
        """
    )
    key_sql = title_key_sql("rec.title")
    await conn.execute(
        f"""
        INSERT INTO song_rec (
            recording_mbid, artist_mbid, title, title_key, group_key, work_mbid,
            kind, year, studio_date, type_rank, editions, isrcs
        )
        SELECT rec.mbid,
               rec.artist_mbid,
               rec.title,
               {key_sql},
               CASE
                 WHEN rw.work_mbid IS NOT NULL
                 THEN 'w:' || rec.artist_mbid::text || ':' || rw.work_mbid::text
                 ELSE 't:' || rec.artist_mbid::text || ':' || ({key_sql})
               END,
               rw.work_mbid,
               CASE
                 WHEN COALESCE(rw.attributes, '{{}}') && ARRAY['cover']
                   THEN 'cover'
                 WHEN COALESCE(rw.attributes, '{{}}') && ARRAY['live']
                   OR rec.comment ~* '\\ylive\\y'
                   OR rec.title ~* $t$[\(\[][^\)\]]*\ylive\y[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*\ylive\y.*$t$
                   OR COALESCE(f.secondary_types, '{{}}') && ARRAY['Live']
                   THEN 'live'
                 WHEN rec.comment ~* $$taylor'?s version$$
                   OR rec.title ~* $t$[\(\[][^\)\]]*taylor'?s version[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*taylor'?s version.*$t$
                   OR rec.comment ~* 're-?recording'
                   OR rec.title ~* $t$[\(\[][^\)\]]*re-?recording[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*re-?recording.*$t$
                   THEN 'rerecording'
                 WHEN COALESCE(rw.attributes, '{{}}') && ARRAY['instrumental']
                   OR rec.comment ~* '\\yinstrumental\\y'
                   OR rec.title ~* $t$[\(\[][^\)\]]*\yinstrumental\y[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*\yinstrumental\y.*$t$
                   THEN 'instrumental'
                 WHEN rec.comment ~* '\\ydemo\\y'
                   OR rec.title ~* $t$[\(\[][^\)\]]*\ydemo\y[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*\ydemo\y.*$t$
                   OR COALESCE(f.secondary_types, '{{}}') && ARRAY['Demo']
                   THEN 'demo'
                 WHEN rec.comment ~* '\\yacoustic\\y'
                   OR rec.title ~* $t$[\(\[][^\)\]]*\yacoustic\y[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*\yacoustic\y.*$t$
                   THEN 'acoustic'
                 WHEN rec.comment ~* '\\yremix\\y'
                   OR rec.title ~* $t$[\(\[][^\)\]]*\yremix\y[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*\yremix\y.*$t$
                   OR COALESCE(f.secondary_types, '{{}}') && ARRAY['Remix']
                   THEN 'remix'
                 WHEN rec.comment ~* 'remaster'
                   OR rec.title ~* $t$[\(\[][^\)\]]*remaster[^\)\]]*[\)\]]\s*$t$
                   OR rec.title ~* $t$\s[-–]\s+.*remaster.*$t$
                   THEN 'remaster'
                 WHEN COALESCE(rw.attributes, '{{}}')
                        && ARRAY['karaoke', 'medley', 'partial']
                   THEN 'other'
                 ELSE 'original'
               END,
               f.year,
               s.studio_date,
               s.type_rank,
               COALESCE(s.editions, 0),
               COALESCE(i.n, 0)
        FROM mb_recording rec
        LEFT JOIN LATERAL (
            SELECT work_mbid, attributes
            FROM mb_recording_work w
            WHERE w.recording_mbid = rec.mbid
            ORDER BY w.work_mbid
            LIMIT 1
        ) rw ON true
        LEFT JOIN song_first f ON f.recording_mbid = rec.mbid
        LEFT JOIN song_studio s ON s.recording_mbid = rec.mbid
        LEFT JOIN (
            SELECT recording_mbid, count(*)::integer AS n
            FROM mb_isrc
            GROUP BY recording_mbid
        ) i ON i.recording_mbid = rec.mbid
        WHERE rec.artist_mbid IS NOT NULL
          AND rec.title <> ''
        """
    )
    # Cover by another artist is their own song with kind=cover, shared work.
    await conn.execute(
        """
        UPDATE song_rec rec
        SET kind = 'cover'
        FROM (
            SELECT DISTINCT ON (r.work_mbid) r.work_mbid, r.artist_mbid
            FROM song_rec r
            LEFT JOIN song_first f ON f.recording_mbid = r.recording_mbid
            WHERE r.work_mbid IS NOT NULL
              AND r.kind = 'original'
              AND COALESCE(NULLIF(r.studio_date, ''), CASE WHEN f.status = 'Official' THEN NULLIF(f.first_date, '') END) IS NOT NULL
            ORDER BY r.work_mbid,
                     COALESCE(NULLIF(r.studio_date, ''), CASE WHEN f.status = 'Official' THEN NULLIF(f.first_date, '') END),
                     r.type_rank NULLS LAST,
                     r.recording_mbid
        ) home
        WHERE rec.work_mbid = home.work_mbid
          AND rec.artist_mbid <> home.artist_mbid
          AND rec.kind IN ('original', 'remaster', 'other')
        """
    )
    ambiguous = int(
        await conn.fetchval(
            """
            SELECT count(*) FROM song_rec rec
            JOIN (
                SELECT artist_mbid, title_key
                FROM song_rec
                WHERE work_mbid IS NOT NULL
                GROUP BY artist_mbid, title_key
                HAVING count(DISTINCT work_mbid) > 1
            ) many ON many.artist_mbid = rec.artist_mbid
                  AND many.title_key = rec.title_key
            WHERE rec.work_mbid IS NULL
            """
        )
        or 0
    )
    await conn.execute(
        """
        UPDATE song_rec rec
        SET group_key = uniq.group_key,
            work_mbid = uniq.work_mbid
        FROM (
            SELECT artist_mbid, title_key,
                   min(group_key) AS group_key,
                   (array_agg(work_mbid))[1] AS work_mbid
            FROM song_rec
            WHERE work_mbid IS NOT NULL
            GROUP BY artist_mbid, title_key
            HAVING count(DISTINCT work_mbid) = 1
        ) uniq
        WHERE rec.work_mbid IS NULL
          AND rec.artist_mbid = uniq.artist_mbid
          AND rec.title_key = uniq.title_key
        """
    )
    await conn.execute(
        """
        INSERT INTO song_load (group_key, artist_mbid, title, work_mbid)
        SELECT rec.group_key,
               rec.artist_mbid,
               min(rec.title),
               (array_agg(rec.work_mbid))[1]
        FROM song_rec rec
        GROUP BY rec.group_key, rec.artist_mbid
        """
    )
    await conn.execute(
        """
        INSERT INTO song_version_load (song_id, recording_mbid, kind, year)
        SELECT s.id, rec.recording_mbid, rec.kind, rec.year
        FROM song_rec rec
        JOIN song_load s ON s.group_key = rec.group_key
        """
    )
    await conn.execute(
        """
        UPDATE song_load s
        SET original_recording_mbid = picked.recording_mbid,
            original_year = picked.year,
            title = picked.title
        FROM (
            SELECT DISTINCT ON (v.song_id)
                v.song_id,
                rec.recording_mbid,
                rec.year,
                rec.title
            FROM song_version_load v
            JOIN song_rec rec ON rec.recording_mbid = v.recording_mbid
            LEFT JOIN song_first f ON f.recording_mbid = rec.recording_mbid
            WHERE v.kind = 'original'
              -- Soundtrack and compilation — yes (FT-541), bootleg — no.
              AND (rec.studio_date IS NOT NULL OR f.status = 'Official')
            ORDER BY v.song_id,
                     rec.type_rank NULLS LAST,
                     rec.studio_date NULLS LAST,
                     rec.isrcs DESC,
                     rec.editions DESC,
                     rec.recording_mbid
        ) picked
        WHERE s.id = picked.song_id
        """
    )
    await conn.execute("ALTER TABLE song_load DROP COLUMN group_key")
    songs = int(await conn.fetchval("SELECT count(*) FROM song_load") or 0)
    versions = int(await conn.fetchval("SELECT count(*) FROM song_version_load") or 0)
    without = int(
        await conn.fetchval(
            "SELECT count(*) FROM song_load WHERE original_recording_mbid IS NULL"
        )
        or 0
    )
    kind_rows = await conn.fetch(
        "SELECT kind, count(*)::bigint AS n FROM song_version_load "
        "GROUP BY kind ORDER BY kind"
    )
    by_kind = {str(row["kind"]): int(row["n"]) for row in kind_rows}
    for kind in KINDS:
        by_kind.setdefault(kind, 0)
    return {
        "songs": songs,
        "versions": versions,
        "without_original": without,
        "ambiguous_unjoined": ambiguous,
        "by_kind": by_kind,
    }


async def _swap(conn: asyncpg.Connection, has_mb: bool, hot_on_main: bool) -> None:
    def ts(name: str) -> str:
        return search_indexes.relation_tablespace(name, has_mb=has_mb, hot_on_main=hot_on_main)

    async with conn.transaction():
        await conn.execute("DROP TABLE IF EXISTS song_version")
        await conn.execute("DROP TABLE IF EXISTS song CASCADE")
        if _swap_hook is not None:
            maybe = _swap_hook()
            if asyncio.iscoroutine(maybe):
                await maybe
        await conn.execute("ALTER TABLE song_load RENAME TO song")
        await conn.execute(
            "ALTER INDEX IF EXISTS song_load_pkey RENAME TO song_pkey"
        )
        await conn.execute("ALTER TABLE song_version_load RENAME TO song_version")
        await conn.execute(
            "ALTER INDEX IF EXISTS song_version_load_pkey RENAME TO song_version_pkey"
        )
        await conn.execute(
            "ALTER INDEX IF EXISTS song_version_load_song RENAME TO song_version_song"
        )
        await conn.execute(
            f"CREATE INDEX IF NOT EXISTS song_artist ON song (artist_mbid){ts('song_artist')}"
        )
        await conn.execute(
            f"CREATE INDEX IF NOT EXISTS song_work ON song (work_mbid){ts('song_work')}"
        )
        await conn.execute(
            f"CREATE INDEX IF NOT EXISTS song_version_kind ON song_version (kind){ts('song_version_kind')}"
        )
        await conn.execute(
            f"CREATE INDEX IF NOT EXISTS song_title_trgm ON song USING gin (title gin_trgm_ops){ts('song_title_trgm')}"
        )
        await conn.execute(
            f"CREATE INDEX IF NOT EXISTS song_title_lower ON song ({search_indexes.SONG_TITLE_LOWER}){ts('song_title_lower')}"
        )


async def build(database_url: str) -> dict[str, Any]:
    """Recalculate song and song_version. Swap is a single transaction."""
    began = time.monotonic()
    conn = await asyncpg.connect(database_url)
    try:
        await conn.execute(f"SET maintenance_work_mem = '{MAINTENANCE_WORK_MEM}'")
        has_mb = await _has_mb(conn)
        from app.mbcopy import hot_fits_main_volume
        hot_on_main = await hot_fits_main_volume(conn, has_mb=has_mb)
        await _create_load(conn, has_mb, hot_on_main)
        try:
            summary = await _fill(conn)
            # The swap renumbers every song id, so re-point the identities in
            # the same transaction; a conflict fails the rebuild as a whole.
            async with conn.transaction():
                await _swap(conn, has_mb, hot_on_main)
                from app.mbcopy import _assign_song_identities
                await _assign_song_identities(conn)
        except Exception:
            await _drop_load(conn)
            raise
        await conn.execute("DROP TABLE IF EXISTS song_rec")
        await conn.execute("DROP TABLE IF EXISTS song_first")
        await conn.execute("DROP TABLE IF EXISTS song_studio")
        duration_ms = int((time.monotonic() - began) * 1000)
        summary["duration_ms"] = duration_ms
        by_kind = summary["by_kind"]
        logger.info(
            "catalog songs: %d songs, %d versions, original %d, live %d, "
            "remaster %d, remix %d, rerecording %d, cover %d, without original %d, %d ms",
            summary["songs"],
            summary["versions"],
            by_kind.get("original", 0),
            by_kind.get("live", 0),
            by_kind.get("remaster", 0),
            by_kind.get("remix", 0),
            by_kind.get("rerecording", 0),
            by_kind.get("cover", 0),
            summary["without_original"],
            duration_ms,
        )
        return summary
    finally:
        await conn.close()


def main(argv: list[str]) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
    parser = argparse.ArgumentParser(prog="python -m app.catalog_songs")
    sub = parser.add_subparsers(dest="cmd")
    sub.add_parser("build")
    args = parser.parse_args(argv)
    if args.cmd != "build":
        parser.print_help()
        return 2
    url = os.environ.get("DATABASE_URL")
    if not url:
        print("DATABASE_URL is not set", file=sys.stderr)
        return 2
    result = asyncio.run(build(url))
    print(json.dumps(result, ensure_ascii=False, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
