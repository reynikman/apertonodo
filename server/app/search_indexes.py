"""Exact search indexes on MusicBrainz copy: `lower(...)` on btree.

Loaders (`mbcopy`, `catalog_songs`) build them automatically on every load.
This module is for a database populated before these indexes were added:
`python -m app.search_indexes` builds missing ones CONCURRENTLY, i.e.
without read locks, and subsequent runs do nothing. This cannot be done via
migration: migrations run inside a transaction at container start, and indexing
30M rows takes minutes — server startup would hang.

Names match those generated by the loader (with `_new`: it indexes
`*_new` and only renames the table) so that the next load
does not create a duplicate index.
"""

from __future__ import annotations

import asyncio
import os
import sys

import asyncpg

MB_INDEXES = (
    ("mb_artist_new_name_lower", "mb_artist", "lower(name) text_pattern_ops"),
    ("mb_artist_alias_new_name_lower", "mb_artist_alias", "lower(name) text_pattern_ops"),
    ("mb_recording_new_title_lower", "mb_recording", "lower(title) text_pattern_ops"),
    ("mb_isrc_new_isrc", "mb_isrc", "isrc"),
)
SONG_TITLE_LOWER = "lower(title) text_pattern_ops"

# Hot search relations (FT-440), centralized: exact names under which
# mbcopy.py and catalog_songs.py create these tables and indexes. Cold search
# on production on 30.09 was disk-bound on HDD — hot relations move to main volume
# when there is room (mbcopy._hot_fits_main_volume), otherwise remain in tablespace mb.
HOT_RELATIONS = frozenset(
    {
        "mb_artist_new",
        "mb_artist_alias_new",
        "mb_recording_new",
        "mb_release_group_new",
        "mb_release_new",
        "mb_medium_new",
        "song_load",
        "song_version_load",
        "mb_artist_new_name_lower",
        "mb_artist_new_name_trgm",
        "mb_artist_alias_new_name_lower",
        "mb_recording_new_title_lower",
        "mb_release_group_new_artist",
        "mb_release_new_group_mbid",
        "mb_medium_new_release",
        "mb_track_new_recording",  # Song cover art (FT-512).
        "song_version_load_song",
        "song_artist",
        "song_title_lower",
        "song_title_trgm",
    }
)


# Renames during table swap (mbcopy._rename_loaded_tables,
# catalog_songs._swap): name of table/index from HOT_RELATIONS (as created)
# -> live production relation name. Only tables and a single index
# with manual ALTER INDEX RENAME are renamed; mb_*_new_... and
# song_artist/song_title_lower/song_title_trgm indexes are created directly under
# their final names and are not in this mapping.
_LIVE_RENAME = {
    "mb_artist_new": "mb_artist",
    "mb_artist_alias_new": "mb_artist_alias",
    "mb_recording_new": "mb_recording",
    "mb_release_group_new": "mb_release_group",
    "mb_release_new": "mb_release",
    "mb_medium_new": "mb_medium",
    "song_load": "song",
    "song_version_load": "song_version",
    "song_version_load_song": "song_version_song",
}


def live_name(name: str) -> str:
    """The name a `HOT_RELATIONS` entry carries on the live database today."""
    return _LIVE_RENAME.get(name, name)


def relation_tablespace(name: str, *, has_mb: bool, hot_on_main: bool) -> str:
    """TABLESPACE clause for a table/index created under this name.

    Hot relations (`HOT_RELATIONS`) go on the main volume when there is room
    for them (`hot_on_main`); everything else, and hot relations when there
    is not, go to tablespace mb as before.
    """
    if has_mb and name in HOT_RELATIONS and hot_on_main:
        return ""
    return " TABLESPACE mb" if has_mb else ""


def _statements() -> list[str]:
    # All four belong to hot search relations (HOT_RELATIONS): no TABLESPACE mb.
    return [
        *(f"CREATE INDEX CONCURRENTLY IF NOT EXISTS {name} ON {table} ({expr})" for name, table, expr in MB_INDEXES),
        f"CREATE INDEX CONCURRENTLY IF NOT EXISTS song_title_lower ON song ({SONG_TITLE_LOWER})",
    ]


async def ensure(conn: asyncpg.Connection) -> list[str]:
    """Build missing indexes; return names of built indexes."""
    built = []
    for sql in _statements():
        name = sql.split("IF NOT EXISTS ", 1)[1].split()[0]
        # Aborted CONCURRENTLY leaves an invalid index, and IF NOT EXISTS
        # would silently accept it; drop and rebuild in that case.
        valid = await conn.fetchval(
            "SELECT i.indisvalid FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid "
            "WHERE c.relname = $1 AND c.relnamespace = 'public'::regnamespace",
            name,
        )
        if valid:
            continue
        if valid is False:
            await conn.execute(f"DROP INDEX CONCURRENTLY IF EXISTS {name}")
        await conn.execute(sql)
        built.append(name)
    return built


async def _main(url: str) -> list[str]:
    conn = await asyncpg.connect(url)
    try:
        await conn.execute("SET maintenance_work_mem = '1GB'")
        return await ensure(conn)
    finally:
        await conn.close()


if __name__ == "__main__":
    url = os.environ.get("DATABASE_URL")
    if not url:
        print("DATABASE_URL is not set", file=sys.stderr)
        raise SystemExit(2)
    print("built:", ", ".join(asyncio.run(_main(url))) or "nothing")
