-- Song = studio recording, rest are versions (catalog v2, stage V3).
--
-- Rebuild: `python -m app.catalog_songs build`. No foreign key to mb_*:
-- mbcopy loader does DROP CASCADE on live mb_* and would drop these tables.
-- recording comment and recording->work relation attributes go here too: empty until
-- next copy load completes.
--
-- Tablespace mb is not included here, as in 019_mb.sql. First build replaces
-- tables with twin tables inside mb if tablespace exists.

ALTER TABLE mb_recording ADD COLUMN IF NOT EXISTS comment text NOT NULL DEFAULT '';

ALTER TABLE mb_recording_work ADD COLUMN IF NOT EXISTS attributes text[] NOT NULL DEFAULT '{}';

CREATE TABLE IF NOT EXISTS song (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_mbid uuid NOT NULL,
    title text NOT NULL,
    work_mbid uuid,
    original_recording_mbid uuid,
    original_year smallint
);

CREATE INDEX IF NOT EXISTS song_artist ON song (artist_mbid);

CREATE INDEX IF NOT EXISTS song_work ON song (work_mbid);

CREATE TABLE IF NOT EXISTS song_version (
    song_id bigint NOT NULL,
    recording_mbid uuid NOT NULL PRIMARY KEY,
    kind text NOT NULL,
    year smallint
);

CREATE INDEX IF NOT EXISTS song_version_song ON song_version (song_id);

CREATE INDEX IF NOT EXISTS song_version_kind ON song_version (kind);
